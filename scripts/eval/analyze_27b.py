#!/usr/bin/env python3
"""
analyze_27b.py — does a bigger model, or three retrieved train examples, help on VM14K?

Reads the two Kaggle runs from scripts/eval/kaggle_27b.py (Qwen3.5-27B NF4, letter-logit scored) and
compares them with Qwen3.5-9B scored the same way and with the strong generation-scored models. The
retrieval gain is split by how close the nearest train item is, since near-copies of a test item can
sit in train (the split groups exact stems only). Writes reports/eval/QWEN27B.md.

    python scripts/eval/analyze_27b.py
"""
import csv
import os
import sys
from math import comb

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import roc_auc_score

HERE = os.path.dirname(__file__)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "training"))
from analyze_finetune import acc_at_coverage, conf, ece, item_text, paired_row, pct, table  # noqa: E402
from run_eval import LETTERS, RUNS_DIR, load_rows  # noqa: E402
from summarize_eval import PAPER_TOPIC_MODELS, PAPER_TOPIC_PASS1, load_run  # noqa: E402

OUT_MD = os.path.join(RUNS_DIR, "..", "QWEN27B.md")
REVIEW_CSV = os.path.join(RUNS_DIR, "..", "VM14K_125_phan_loai_so_bo.csv")
KEY_WRONG = {"Đáp án chuẩn sai", "Kiến thức cũ / đã thay đổi"}
KEY_RIGHT = {"Model sai, đáp án chuẩn đúng", "Đúng theo phác đồ / thực hành VN"}
RUNS = {
    "Qwen3.5-9B zero-shot": "hf-logit__Qwen_Qwen3.5-9B__paper__test",
    "Qwen3.5-27B zero-shot": "hf-logit__Qwen_Qwen3.5-27B-bnb4__paper__test",
    "Qwen3.5-27B + 3 retrieved": "hf-logit__Qwen_Qwen3.5-27B-bnb4__fewshot3-tfidf__test",
}
STRONG = {"Gemma-4-31B": "nvidia__google_gemma-4-31b-it__paper__test",
          "DeepSeek-v4.1-flash": "nvidia__deepseek-ai_deepseek-v4.1-flash__paper__test"}
SEVEN = list(STRONG.values()) + ["gemma4_12b__paper__test", "qwen3.5_9b__paper__test", "qwen3_8b__paper__test",
                                 "llama3.1_8b__paper__test", "medgemma_4b__paper__test"]
HDR = ["comparison (A → B)", "n", "A %", "B %", "B − A", "only A right", "only B right", "p"]


def load(name):
    return {r["id"]: r for r in load_run(os.path.join(RUNS_DIR, name + ".jsonl"))}


def binom_greater(k, n, p0):
    """One-sided exact binomial p-value: P(X >= k) when X ~ Bin(n, p0)."""
    return sum(comb(n, j) * p0 ** j * (1 - p0) ** (n - j) for j in range(k, n + 1))


def main():
    runs = {k: load(v) for k, v in RUNS.items()}
    gm, ds = (load(v) for v in STRONG.values())
    seven = [load(n) for n in SEVEN]
    test, train = load_rows("test", None, 0), load_rows("train", None, 0)
    ids = [r["id"] for r in test]
    b9, zs, rag = runs.values()

    lines = ["# VM14K: Qwen3.5-27B, zero-shot and with three retrieved train examples", "",
             "Generated by `scripts/eval/analyze_27b.py` from `scripts/eval/kaggle_27b.py` (Kaggle 2 x T4, NF4 "
             "4-bit weights, fp16 compute, letter-logit scoring after the paper's Fig. 6 prompt, thinking off). "
             "`+ 3 retrieved` puts the three train questions closest to the test item (TF-IDF over question + "
             "options) before it as earlier chat turns, with their keys and shuffled options. No training.", ""]
    rows = []
    for label, run in runs.items():
        recs = [run[i] for i in ids]
        rows.append([label, len(recs), pct(sum(r["correct"] for r in recs), len(recs)),
                     f"{100 * sum(r['pred'] == 'A' for r in recs) / len(recs):.1f}", f"{100 * ece(recs):.1f}",
                     f"{100 * acc_at_coverage(recs, 0.5):.1f}"])
    lines += ["## 1. Overall", ""]
    lines += table(["run", "n", "accuracy [95% CI]", "picks A %", "ECE %", "acc. on 50% most confident"], rows)
    lines += table(HDR, [paired_row("9B zero-shot → 27B zero-shot", b9, zs, ids),
                         paired_row("27B zero-shot → 27B + 3 retrieved", zs, rag, ids),
                         paired_row("Gemma-4-31B → 27B + 3 retrieved", gm, rag, ids),
                         paired_row("DeepSeek-v4.1-flash → 27B + 3 retrieved", ds, rag, ids)])

    # Same retrieval as kaggle_27b.py, so the nearest item here is the closest example the model saw.
    vec = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True).fit([item_text(r) for r in train + test])
    sim = (vec.transform([item_text(r) for r in test]) @ vec.transform([item_text(r) for r in train]).T).tocsr()
    near = dict(zip(ids, sim.max(axis=1).toarray().ravel()))
    nearest = dict(zip(ids, (train[j] for j in sim.argmax(axis=1).A1)))
    key_text = lambda r: " ".join(r["options"][r["answer_index"]].lower().split())  # noqa: E731
    same_key = {r["id"] for r in test if key_text(r) == key_text(nearest[r["id"]])}
    lines += ["## 2. Is the retrieval gain carried by near-copies?", "",
              "Test items binned by similarity to the closest train item (= the closest example shown). "
              "`same key text` = that train item's keyed answer reads the same as the test item's.", ""]
    rows = []
    for lo, hi in ((0.0, 0.3), (0.3, 0.5), (0.5, 0.8), (0.8, 1.01)):
        bids = [i for i in ids if lo <= near[i] < hi]
        rows.append(paired_row(f"similarity {lo:.1f}–{min(hi, 1):.1f}", zs, rag, bids))
    rows.append(paired_row("closest example has the same key text", zs, rag, [i for i in ids if i in same_key]))
    rows.append(paired_row("closest example has another key text", zs, rag, [i for i in ids if i not in same_key]))
    lines += table(["items"] + HDR[1:], rows)

    disputed = [i for i in ids if ds[i]["pred"] and ds[i]["pred"] == gm[i]["pred"] and not ds[i]["correct"]]
    allwrong = [i for i in ids if all(i in s and not s[i]["correct"] for s in seven)]
    assert (len(disputed), len(allwrong)) == (238, 125), (len(disputed), len(allwrong))
    rest = [i for i in ids if i not in set(disputed) | set(allwrong)]
    lines += ["## 3. Contested items: does retrieval pull the model toward the key?", "",
              "`agree w/ strong` = picks the option DeepSeek-v4.1-flash and Gemma-4-31B both chose. Fine-tuning "
              "did not move key agreement on the 238 (FINETUNE.md §4); retrieval shows the model the train keys "
              "directly.", ""]
    rows = []
    for label, run in runs.items():
        rows.append([label, pct(sum(run[i]["correct"] for i in disputed), len(disputed)),
                     pct(sum(run[i]["pred"] == ds[i]["pred"] for i in disputed), len(disputed)),
                     pct(sum(run[i]["correct"] for i in allwrong), len(allwrong)),
                     pct(sum(run[i]["correct"] for i in rest), len(rest))])
    lines += table(["run", "238 disputed: = key", "238 disputed: agree w/ strong", "125 all-wrong: = key",
                    f"other {len(rest)}: = key"], rows)
    lines += table(HDR, [paired_row("238 disputed, key agreement: 27B → 27B + 3 retrieved", zs, rag, disputed),
                         paired_row("125 all-wrong, key agreement: 27B → 27B + 3 retrieved", zs, rag, allwrong),
                         paired_row(f"other {len(rest)}: 27B → 27B + 3 retrieved", zs, rag, rest)])
    sim_d = sum(near[i] >= 0.5 for i in disputed)
    lines += [f"{sim_d} of the 238 disputed items have a train item at similarity ≥ 0.5 "
              f"(all test: {100 * sum(near[i] >= 0.5 for i in ids) / len(ids):.1f}%).", ""]

    lines += ["## 4. Answer when confident, otherwise ask DeepSeek-v4.1-flash", ""]
    order = sorted(ids, key=lambda i: conf(rag[i]))
    rows = []
    for share in (0.25, 0.5):
        routed = set(order[:round(share * len(ids))])
        kept = [i for i in ids if i not in routed]
        rows.append([f"{100 * share:.0f}%",
                     f"{100 * sum(ds[i]['correct'] if i in routed else rag[i]['correct'] for i in ids) / len(ids):.1f}",
                     f"{100 * sum(rag[i]['correct'] for i in kept) / len(kept):.1f}",
                     f"{100 * sum(ds[i]['correct'] for i in kept) / len(kept):.1f}"])
    lines += table(["sent to DeepSeek", "accuracy", "27B + 3 retrieved on what it kept", "DeepSeek on those items"],
                   rows)

    q32, r1 = PAPER_TOPIC_MODELS.index("Qwen3-32B"), PAPER_TOPIC_MODELS.index("DeepSeek-R1")
    lines += ["## 5. The paper's top-10 topics (Table 4)", "",
              "Paper numbers are pass@1 on the uncleaned 12,488-row release, not on these items: a reference, not a "
              "matched comparison. `p` = one-sided exact binomial test of 27B + 3 retrieved against the paper's "
              "Qwen3-32B value taken as fixed; 10 topics, so p < 0.005 survives Bonferroni.", ""]
    rows = []
    for t, vals in PAPER_TOPIC_PASS1.items():
        tid = [r["id"] for r in test if t in r["medical_topic"]]
        acc = lambda run: f"{100 * sum(run[i]['correct'] for i in tid) / len(tid):.1f}"  # noqa: E731
        k = sum(rag[i]["correct"] for i in tid)
        rows.append([t, len(tid), f"{100 * sum(near[i] >= 0.3 for i in tid) / len(tid):.0f}%", acc(zs), acc(rag),
                     acc(gm), acc(ds), f"{vals[q32]:.1f}", f"{vals[r1]:.1f}",
                     f"{binom_greater(k, len(tid), vals[q32] / 100):.3f}"])
    lines += table(["topic", "n", "train item ≥ 0.3", "27B zero-shot", "27B + 3 retrieved", "Gemma-4-31B",
                    "DeepSeek-v4.1-flash", "paper Qwen3-32B", "paper DeepSeek-R1", "p (27B + 3 > Qwen3-32B)"], rows)

    if os.path.exists(REVIEW_CSV):
        with open(REVIEW_CSV, encoding="utf-8-sig") as fh:
            review = {r["id"]: r for r in csv.DictReader(fh)}
        labelled = [(i, r["Phân loại sơ bộ (AI)"] in KEY_WRONG) for i, r in review.items()
                    if r["Phân loại sơ bộ (AI)"] in KEY_WRONG | KEY_RIGHT]
        lines += ["## 6. Does a model's probability on the key flag a wrong key?", "",
                  f"On the {len(labelled)} of the 125 all-wrong items that the AI pre-review "
                  "(`VM14K_125_phan_loai_so_bo.csv`) labels key wrong or key right: AUROC of 1 − P(key). The pre-review "
                  "saw the models' answers, so this is optimistic until clinicians give the labels.", ""]
        rows = []
        for label, run in list(runs.items())[1:] + [("JEV-9B", load("jev9b__autotrust_JEV-9B__choice__test"))]:
            p_key = lambda i: (run[i].get("probs_orig") or run[i]["probs"])[LETTERS.index(run[i]["gold"])]  # noqa: E731
            rows.append([label, f"{roc_auc_score([y for _, y in labelled], [1 - p_key(i) for i, _ in labelled]):.2f}"])
        lines += table(["run", "AUROC"], rows)
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
