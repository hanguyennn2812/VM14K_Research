#!/usr/bin/env python3
"""
analyze_decision.py — off-the-shelf decision models on VM14K against letter-logit runs of their backbones.

Reads the decision__* runs written by modal_decision.py and compares each with the zero-shot
letter-logit run of the same Qwen3.5 backbone where one exists (hf-logit__*), with JEV-9B, and with
the strong models. Columns as in FINETUNE.md / JEV.md; `undisputed` drops the 268 items whose key the
models dispute (VOTE.md). Writes reports/eval/DECISION.md.

    python scripts/eval/analyze_decision.py
"""
import math
import os
import sys

HERE = os.path.dirname(__file__)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "training"))
from analyze_finetune import acc_at_coverage, ece, paired_row, pct, table  # noqa: E402
from run_eval import RUNS_DIR, load_rows  # noqa: E402
from summarize_eval import load_run  # noqa: E402

OUT_MD = os.path.join(RUNS_DIR, "..", "DECISION.md")
# decision model -> (label, letter-logit run of the same backbone or None)
DECISION = {
    "vllm-sr_d3-edge": ("d3-edge 0.6B", None),
    "vllm-sr_d3-lite": ("d3-lite 0.8B", None),
    "vllm-sr_d3-nano": ("d3-nano 2B", "hf-logit__Qwen_Qwen3.5-2B__paper__test"),
    "vllm-sr_d3-mini": ("d3-mini 4B", None),
    "vllm-sr_d3-flash": ("d3-flash 9B", "hf-logit__Qwen_Qwen3.5-9B__paper__test"),
    "vllm-sr_d3": ("d3 27B (Qwen3.8-27B)", None),  # no letter-logit run of Qwen3.8-27B
    "lion-ai_MedDecider-27B": ("MedDecider-27B (medical LoRA, Qwen3.8-27B)", None),
}
CONTEXTS = {"": "none", "-shots": "3 similar train items with keys", "-docs": "3 MoH guideline chunks",
            "-shots+docs": "both"}
REFS = {
    "Qwen3.5-2B letter logits": "hf-logit__Qwen_Qwen3.5-2B__paper__test",
    "Qwen3.5-2B + LoRA letter logits": "hf-logit__Qwen_Qwen3.5-2B+q35-2b-sft-shuf__paper__test",
    "Qwen3.5-2B + jev-torch head (VM14K train)": "jevtorch__Qwen_Qwen3.5-2B__choice__test",
    "Qwen3.5-9B letter logits": "hf-logit__Qwen_Qwen3.5-9B__paper__test",
    "JEV-9B (decision head)": "jev9b__autotrust_JEV-9B__choice__test",
    "Qwen3.5-27B 4-bit letter logits": "hf-logit__Qwen_Qwen3.5-27B-bnb4__paper__test",
    "Gemma-4-31B (generation)": "nvidia__google_gemma-4-31b-it__paper__test",
}
SEVEN = ["nvidia__deepseek-ai_deepseek-v4.1-flash__paper__test", "nvidia__google_gemma-4-31b-it__paper__test",
         "gemma4_12b__paper__test", "qwen3.5_9b__paper__test", "qwen3_8b__paper__test", "llama3.1_8b__paper__test",
         "medgemma_4b__paper__test"]
HDR = ["comparison (A → B)", "n", "A %", "B %", "B − A", "only A right", "only B right", "p"]


def load(name):
    path = os.path.join(RUNS_DIR, name + ".jsonl")
    return {r["id"]: r for r in load_run(path)} if os.path.exists(path) else None


def scaled(recs, t):
    """p ** (1/t), renormalised: temperature scaling on log-probabilities; the argmax is unchanged."""
    out = []
    for r in recs:
        q = [max(p, 1e-12) ** (1 / t) for p in r["probs"]]
        out.append(dict(r, probs=[x / sum(q) for x in q]))
    return out


def fit_temperature(recs):
    """Grid search 0.25..5 for the temperature with the lowest NLL of the key."""
    def nll(t):
        return -sum(math.log(max(r["probs"]["ABCDE".index(r["gold"])], 1e-12)) for r in scaled(recs, t))
    return min((0.25 + 0.05 * k for k in range(96)), key=nll)


def main():
    ids = [r["id"] for r in load_rows("test", None, 0)]
    gm, ds = load(SEVEN[1]), load(SEVEN[0])
    seven = [load(n) for n in SEVEN]
    disputed = {i for i in ids if ds[i]["pred"] and ds[i]["pred"] == gm[i]["pred"] and not ds[i]["correct"]}
    disputed |= {i for i in ids if all(not s[i]["correct"] for s in seven)}
    undisputed = [i for i in ids if i not in disputed]

    runs = {}
    for key, (label, _) in DECISION.items():
        run = load(f"decision__{key}__choice__test")
        if run and all(i in run for i in ids):
            runs[label] = run
    for label, name in REFS.items():
        run = load(name)
        if run and all(i in run for i in ids):
            runs[label] = run

    lines = ["# VM14K: off-the-shelf decision models", "",
             "Generated by `scripts/eval/analyze_decision.py`. Decision runs: `scripts/eval/modal_decision.py`, one Choice "
             "question per item (state = question, criteria = option letters → texts, as for Jev), the model's own "
             "`system_one`, bf16 on an H100, no tuning. Letter-logit runs read the option-letter probabilities after "
             "the paper's prompt. 1,658 test items; `undisputed` = the 1,390 items outside the disputed set.", ""]
    rows = []
    for label, run in runs.items():
        recs = [run[i] for i in ids]
        lat = sorted(r["latency_s"] for r in recs if r.get("latency_s") is not None)
        has_probs = all(r.get("probs") for r in recs)  # generation runs have none
        rows.append([label, pct(sum(r["correct"] for r in recs), len(recs)),
                     f"{100 * sum(run[i]['correct'] for i in undisputed) / len(undisputed):.1f}",
                     f"{100 * sum(r['pred'] == 'A' for r in recs) / len(recs):.1f}",
                     f"{100 * ece(recs):.1f}" if has_probs else "–",
                     f"{100 * acc_at_coverage(recs, 0.5):.1f}" if has_probs else "–",
                     f"{1000 * lat[len(lat) // 2]:.0f}" if lat else "–"])
    lines += table(["run", "accuracy [95% CI]", "undisputed %", "picks A %", "ECE %", "acc. on 50% most confident",
                    "median ms/item"], rows)
    lines += ["Key is A on 29.8% of test items; always-A 29.8%, random 27.6%.", ""]

    pairs = []
    for key, (label, base) in DECISION.items():
        if label in runs and base:
            base_label = next(lbl for lbl, n in REFS.items() if n == base)
            if base_label in runs:
                pairs.append(paired_row(f"{base_label} → {label}", runs[base_label], runs[label], ids))
    for label in ("d3-flash 9B", "d3-mini 4B"):
        if label in runs and "JEV-9B (decision head)" in runs:
            pairs.append(paired_row(f"JEV-9B → {label}", runs["JEV-9B (decision head)"], runs[label], ids))
    for base in ("Qwen3.5-27B 4-bit letter logits", "Gemma-4-31B (generation)"):
        if "d3 27B (Qwen3.8-27B)" in runs and base in runs:
            pairs.append(paired_row(f"{base} → d3 27B", runs[base], runs["d3 27B (Qwen3.8-27B)"], ids))
    jt = "Qwen3.5-2B + jev-torch head (VM14K train)"
    for base in ("Qwen3.5-2B + LoRA letter logits", "d3-nano 2B"):
        if jt in runs and base in runs:
            pairs.append(paired_row(f"{base} → jev-torch head", runs[base], runs[jt], ids))
    if pairs:
        lines += ["## Same backbone: decision head against letter logits (McNemar exact)", ""] + table(HDR, pairs)

    shuf = []
    for key, (label, _) in DECISION.items():
        s = load(f"decision__{key}__choice__test__shuf1")
        if s and label in runs and all(i in s for i in ids):
            same = sum(s[i]["probs_orig"].index(max(s[i]["probs_orig"])) ==
                       runs[label][i]["probs_orig"].index(max(runs[label][i]["probs_orig"])) for i in ids)
            shuf.append([label, f"{100 * sum(s[i]['correct'] for i in ids) / len(ids):.1f}",
                         f"{100 * same / len(ids):.1f}"])
    if shuf:
        lines += ["## Option order: shuffled options (seed 1)", "",
                  "`same answer` = picks the same option text as in the original order."] + [""]
        lines += table(["model", "accuracy shuffled %", "same answer %"], shuf)

    cal = []
    for key, (label, _) in DECISION.items():
        v = load(f"decision__{key}__choice__val")
        if v and label in runs:
            t = fit_temperature([r for r in v.values() if r.get("probs")])
            test = [runs[label][i] for i in ids]
            cal.append([label, f"{t:.2f}", f"{100 * ece(test):.1f}", f"{100 * ece(scaled(test, t)):.1f}"])
    if cal:
        lines += ["## Calibration: one temperature fitted on val (NLL), applied to test", "",
                  "Accuracy is unchanged (same argmax). Qwen3.5-2B + LoRA letter logits: ECE 1.8%.", ""]
        lines += table(["model", "temperature", "test ECE % before", "test ECE % after"], cal)

    val_ids = [r["id"] for r in load_rows("val", None, 0)]
    infect = [r["id"] for r in load_rows("test", None, 0) if "Infectious Diseases" in r["medical_topic"]]
    zero = {s: load(f"decision__vllm-sr_d3__choice__{s}") for s in ("val", "test")}
    ctx = []
    for suffix, label in CONTEXTS.items():
        v, t = load(f"decision__vllm-sr_d3__choice{suffix}__val"), load(f"decision__vllm-sr_d3__choice{suffix}__test")
        if not v:
            continue
        pv = paired_row("", zero["val"], v, val_ids)
        pt = paired_row("", zero["test"], t, ids) if t else None
        ctx.append([label, pv[3], pv[4], pv[7], pt[3] if pt else "–", pt[4] if pt else "–", pt[7] if pt else "–",
                    f"{100 * sum(t[i]['correct'] for i in infect) / len(infect):.1f}" if t else "–"])
    if ctx:
        lines += ["## d3 27B with retrieved context in the state", "",
                  "Context comes before the question in the state (`modal_decision.py --context`), retrieval as in "
                  "`rag_moh.py` over all MoH documents. Chosen on val; `Δ`/`p` against no context (McNemar exact). "
                  f"Infectious Diseases: the {len(infect)} test items of the target topic.", ""]
        lines += table(["context", "val %", "val Δ", "val p", "test %", "test Δ", "test p", "Infectious test %"], ctx)
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
