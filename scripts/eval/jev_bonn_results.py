#!/usr/bin/env python3
"""
jev_bonn_results.py — the real Jev's medical and Vietnamese numbers, without a TypeSafe key.

Deußer, Sparrenberg & Sifa (arXiv 2609.37647) ran jev-1.13.0, Qwen3.8-27B and Gemma-4-E4B on 37
datasets and published the code, per-dataset results and all raw responses (MIT code;
github.com/AppliedMachineLearning-Lab/jev-benchmarking; responses on Zenodo, doi
10.5281/zenodo.23039006, Jev responses licensed for research and analysis only). This script reads
their per-dataset result files and reports the medical slices — PubMedQA and the medical MMLU
subjects — and Belebele's Vietnamese split. None of it is VM14K: it is English medical QA and
Vietnamese reading comprehension.

    python scripts/eval/jev_bonn_results.py      # writes reports/eval/JEV_REAL.md
"""
import json
import os
import urllib.request

BASE = "https://raw.githubusercontent.com/AppliedMachineLearning-Lab/jev-benchmarking/main/results/eval"
MODELS = {"Jev 1.13 (TypeSafe)": "", "Qwen3.8-27B": "open_models/Qwen__Qwen3.8-27B/",
          "Gemma-4-E4B": "open_models/google__gemma-4-E4B-it/"}
MED = ["anatomy", "clinical_knowledge", "college_biology", "college_medicine", "medical_genetics", "nutrition",
       "professional_medicine", "virology"]
OUT_MD = os.path.join(os.path.dirname(__file__), "..", "..", "reports", "eval", "JEV_REAL.md")


def fetch(prefix, task):
    with urllib.request.urlopen(f"{BASE}/{prefix}{task}.json", timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def head(res):
    return res["heads"].get("answer") or next(iter(res["heads"].values()))


def main():
    rows = []
    for name, prefix in MODELS.items():
        pub, mmlu, bele = (fetch(prefix, t) for t in ("pubmedqa", "mmlu", "belebele"))
        sub = mmlu["subsets"]
        n_med = sum(sub[k]["n"] for k in MED)
        med = sum(sub[k]["primary"] * sub[k]["n"] for k in MED) / n_med
        vie = bele["subsets"]["vie_Latn"]["primary"]
        rows.append([name, f"{100 * head(pub)['accuracy']:.1f}", f"{100 * head(pub)['ece']:.1f}",
                     f"{100 * head(pub)['sel_acc@50']:.1f}", f"{100 * med:.1f}", f"{100 * head(mmlu)['ece']:.1f}",
                     f"{100 * vie:.1f}", f"{100 * bele['subsets']['eng_Latn']['primary']:.1f}"])
    lines = ["# The real Jev on medical QA and Vietnamese (from the Bonn benchmark release)", "",
             "Generated by `scripts/eval/jev_bonn_results.py` from the per-dataset results that Deußer, Sparrenberg & "
             "Sifa published with arXiv 2609.37647 (jev-1.13.0; open models scored by next-token probabilities). "
             "PubMedQA: 1,000 yes/no/maybe questions. MMLU medical: anatomy, clinical knowledge, college biology, "
             f"college medicine, medical genetics, nutrition, professional medicine, virology ({n_med} questions). "
             "Belebele: 900 reading-comprehension items per language. English benchmarks may be in the models' "
             "training data; none of this is VM14K.", "",
             "| model | PubMedQA acc % | PubMedQA ECE % | PubMedQA acc. on 50% most confident | MMLU medical acc % "
             "| MMLU (all) ECE % | Belebele Vietnamese % | Belebele English % |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows] + [""]
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
