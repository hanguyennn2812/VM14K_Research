#!/usr/bin/env python3
"""
analyze_context.py — tables for PLAN_2026-11-09 (RAG for d3-flash 9B on Infectious Diseases), T3.

Reads reports/eval/runs/decision__vllm-sr_d3-flash__choice-<cond>__{val-infect,pairs,test-infect}.jsonl and writes
the generated tables between the markers of reports/eval/CONTEXT_SMALL_20261109.md (the rest of the file is hand-written
and kept).  Table 1: val-infect by condition (n, %, Wilson 95% CI, delta vs zero, paired-bootstrap CI, wins/losses,
McNemar exact p), with the random and always-A baselines of the same items.  Table 2: the `top_sim` gate (GATES of
rag_moh.py), picked on val.  Table 3 (H3): delta by the best TF-IDF train-question similarity, >= 0.3 or < 0.3.
Table 4 (H2): fact-pair probe by condition and group.  Table 5 (--test, T6 only): the one test run.
Verdicts H1/H2/H3 follow the plan's declared thresholds.

    python scripts/eval/analyze_context.py                # val + probe tables
    python scripts/eval/analyze_context.py --test         # also the single test run (T6)
    python scripts/eval/analyze_context.py --selfcheck
"""
import argparse
import json
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from compare_runs import mcnemar_exact  # noqa: E402
from run_eval import RUNS_DIR  # noqa: E402

GATES = [0.0, 0.35, 0.4, 0.45, 0.5, 0.55]  # rag_moh.GATES, copied so this script needs no PDF/sklearn imports
REPORT = os.path.join(HERE, "..", "..", "reports", "eval", "CONTEXT_SMALL_20261109.md")
START, END = "<!-- TABLES START (generated by scripts/eval/analyze_context.py) -->", "<!-- TABLES END -->"
VAL_CONDS = ["zero", "shots", "docs", "shots+docs", "shotsemb", "shotsemb+docs"]
PROBE_CONDS = ["zero", "docs", "own"]
H1_COND, H1_MIN, H3_SPLIT, H2_MIN, PAPER = "shots+docs", 196, 0.3, 15.0, 77.8
NAME = "decision__vllm-sr_d3-flash__choice-{cond}__{scope}.jsonl"


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return 100 * (c - h), 100 * (c + h)


def binom_tail(k, n, p):
    """P(X >= k), X ~ Binomial(n, p)."""
    return sum(math.comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))


def load(cond, scope):
    path = os.path.join(RUNS_DIR, NAME.format(cond=cond, scope=scope))
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return {r["id"]: r for r in map(json.loads, fh)}


def acc(run, ids):
    return 100 * sum(run[i]["correct"] for i in ids) / len(ids)


def baselines(run, ids):
    """(random %, always-A %) over the items: mean 1/n_options and the share of gold == A."""
    return (100 * sum(1 / run[i]["n_options"] for i in ids) / len(ids),
            100 * sum(run[i]["gold"] == "A" for i in ids) / len(ids))


def delta(a, b, ids, reps=2000, seed=20261109):
    """(delta %, CI lo, CI hi, a-only right, b-only right, McNemar p) for b minus a, paired bootstrap over ids."""
    x = [(a[i]["correct"], b[i]["correct"]) for i in ids]
    a_only, b_only = sum(p and not q for p, q in x), sum(q and not p for p, q in x)
    rng, n = random.Random(seed), len(x)
    draws = sorted(100 * sum(q - p for p, q in rng.choices(x, k=n)) / n for _ in range(reps))
    return (100 * (b_only - a_only) / n, draws[int(reps * .025)], draws[int(reps * .975)], a_only, b_only,
            mcnemar_exact(a_only, b_only))


def row(label, run, ids, zero=None):
    k, n = sum(run[i]["correct"] for i in ids), len(ids)
    lo, hi = wilson(k, n)
    cells = f"| {label} | {n} | {k} | {100 * k / n:.1f} | [{lo:.1f}, {hi:.1f}] |"
    if zero is None:
        return cells + " | | | |"
    d, dl, dh, w, l, p = delta(zero, run, ids)
    return cells + f" {d:+.1f} [{dl:+.1f}, {dh:+.1f}] | {l}/{w} | {p:.2g}{' *' if p < 0.05 else ''} |"


HEAD = "| condition | n | right | % | Wilson 95% CI | Δ vs zero [bootstrap 95% CI] | wins/losses | McNemar p |\n|---|---:|---:|---:|---:|---:|---:|---:|"


def gated(with_docs, without, t, ids):
    return {i: with_docs[i] if with_docs[i]["top_sim"] >= t else without[i] for i in ids}


def val_tables(runs, ids, out):
    z = runs["zero"]
    rnd, alw = baselines(z, ids)
    out += [f"### Bảng 1: val Truyền nhiễm, n = {len(ids)}", "",
            f"Mốc ngẫu nhiên {rnd:.1f}%, luôn chọn A {alw:.1f}% (cùng {len(ids)} câu). "
            "'wins/losses' = số câu điều kiện đúng mà zero sai / số câu zero đúng mà điều kiện sai.", "", HEAD]
    out += [row(c, runs[c], ids, None if c == "zero" else z) for c in VAL_CONDS if c in runs]
    out += ["", "### Bảng 2: gate theo `top_sim` (chọn t trên val: độ đúng cao nhất, t nhỏ nhất khi hoà)", ""]
    chosen = {}
    for with_docs, without in (("docs", "zero"), ("shots+docs", "shots"), ("shotsemb+docs", "shotsemb")):
        if with_docs in runs and without in runs:
            res = {t: acc(gated(runs[with_docs], runs[without], t, ids), ids) for t in GATES}
            chosen[with_docs] = max(GATES, key=lambda t: (res[t], -t))
            out += [f"`{with_docs}` (else `{without}`); t chọn = {chosen[with_docs]}", "",
                    "| t | câu có đoạn MoH | độ đúng % |", "|---:|---:|---:|"]
            out += [f"| {t} | {100 * sum(runs[with_docs][i]['top_sim'] >= t for i in ids) / len(ids):.0f}% | "
                    f"{res[t]:.1f} |" for t in GATES] + [""]
    out += [f"### Bảng 3 (H3): Δ so với zero theo độ giống câu train tốt nhất (TF-IDF `shot_sim_max` ≥ {H3_SPLIT})", "",
            "| condition | nhóm | n | zero % | điều kiện % | Δ [bootstrap 95% CI] | wins/losses | p |",
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    h3 = {}
    for c in VAL_CONDS[1:]:
        if c not in runs:
            continue
        for name, grp in ((f"≥ {H3_SPLIT}", [i for i in ids if z[i]["shot_sim_max"] >= H3_SPLIT]),
                          (f"< {H3_SPLIT}", [i for i in ids if z[i]["shot_sim_max"] < H3_SPLIT])):
            if grp:
                d, dl, dh, w, l, p = delta(z, runs[c], grp)
                h3[(c, name[0])] = (d, dl, dh, len(grp))
                out.append(f"| {c} | {name} | {len(grp)} | {acc(z, grp):.1f} | {acc(runs[c], grp):.1f} | "
                           f"{d:+.1f} [{dl:+.1f}, {dh:+.1f}] | {l}/{w} | {p:.2g}{' *' if p < 0.05 else ''} |")
    out.append("")
    return chosen, h3


def probe_tables(runs, out):
    z = runs["zero"]
    ids = sorted(z)
    rnd, alw = baselines(z, ids)
    out += [f"### Bảng 4 (H2): probe fact-pair, n = {len(ids)}", "",
            f"Mốc ngẫu nhiên {rnd:.1f}%, luôn chọn A {alw:.1f}%. Ba nhóm chỉ để mô tả: không train gì nên đều là kiến thức "
            "'chưa học'.", "", HEAD]
    out += [row(c, runs[c], ids, None if c == "zero" else z) for c in PROBE_CONDS if c in runs]
    for g in sorted({z[i]["group"] for i in ids}):
        gi = [i for i in ids if z[i]["group"] == g]
        out += ["", f"Nhóm `{g}` (n = {len(gi)})", "", HEAD]
        out += [row(c, runs[c], gi, None if c == "zero" else z) for c in PROBE_CONDS if c in runs]
    out.append("")
    return delta(z, runs["docs"], ids) if "docs" in runs else None


def verdicts(vruns, ids, h3, probe, out):
    out += ["### Kết luận theo ngưỡng khai báo trước", ""]
    if H1_COND in vruns and "zero" in vruns:
        k = sum(vruns[H1_COND][i]["correct"] for i in ids)
        d = delta(vruns["zero"], vruns[H1_COND], ids)
        h1 = k >= H1_MIN and d[5] < 0.05
        out.append(f"- **H1** (`{H1_COND}` ≥ {H1_MIN}/{len(ids)} và McNemar p < 0,05): {k}/{len(ids)} = "
                   f"{100 * k / len(ids):.1f}%, Δ {d[0]:+.1f}, p = {d[5]:.2g} → **{'ĐẠT' if h1 else 'KHÔNG ĐẠT'}**.")
        low = h3.get((H1_COND, "<"))
        if low:
            out.append(f"- **H3** (Δ ở nhóm < {H3_SPLIT} > 0): n = {low[3]}, Δ {low[0]:+.1f} [{low[1]:+.1f}, {low[2]:+.1f}] → "
                       f"**{'KHÔNG BÁC BỎ' if low[0] > 0 else 'BỊ BÁC BỎ'}** (CI {'chứa' if low[1] <= 0 <= low[2] else 'không chứa'} 0).")
        best = max((c for c in VAL_CONDS[1:] if c in vruns), key=lambda c: sum(vruns[c][i]["correct"] for i in ids))
        gains = [(c, delta(vruns["zero"], vruns[c], ids)) for c in VAL_CONDS[1:] if c in vruns]
        refuted = not any(g[0] >= 2 for _, g in gains) or all(g[1] <= 0 <= g[2] for _, g in gains)
        out.append(f"- Điều kiện cao nhất trên val: `{best}`. Bác bỏ H1 theo mục 3 (không điều kiện nào ≥ +2 hoặc mọi CI chứa 0): "
                   f"{'CÓ' if refuted else 'KHÔNG'}.")
    if probe:
        d, dl, dh, w, l, p = probe
        out.append(f"- **H2** (`docs` − `zero` ≥ {H2_MIN:.0f} điểm, p < 0,05): Δ {d:+.1f} [{dl:+.1f}, {dh:+.1f}], p = {p:.2g} → "
                   f"**{'ĐẠT' if d >= H2_MIN and p < 0.05 else 'KHÔNG ĐẠT'}**.")
    out.append("")


def test_table(out):
    z, c = load("zero", "test-infect"), None
    for cond in VAL_CONDS[1:]:
        c = load(cond, "test-infect") or c
    if not z or not c:
        out += ["### Test: chưa có (T6 chưa chạy)", ""]
        return
    cond = next(k for k in VAL_CONDS[1:] if load(k, "test-infect"))
    ids = sorted(set(z) & set(c))
    k = sum(c[i]["correct"] for i in ids)
    out += [f"### Test Truyền nhiễm — lần chấm test duy nhất, 09/11/2026 (n = {len(ids)})", "", HEAD,
            row("zero", z, ids), row(cond, c, ids, z), "",
            f"Kiểm định nhị thức một phía, H0: độ đúng thật ≤ {PAPER}%: {k}/{len(ids)}, p = "
            f"{binom_tail(k, len(ids), PAPER / 100):.3g}. Số của paper đo trên bản chưa làm sạch, không cùng câu.", ""]


def selfcheck():
    lo, hi = wilson(50, 100)
    assert abs(lo - 40.4) < .1 and abs(hi - 59.6) < .1 and wilson(0, 0) == (0.0, 0.0)
    assert abs(binom_tail(1, 2, .5) - .75) < 1e-12 and abs(binom_tail(0, 5, .3) - 1.0) < 1e-12
    mk = lambda flags: {str(i): {"correct": f, "gold": "A", "n_options": 4, "top_sim": .5, "shot_sim_max": .1 * i}
                        for i, f in enumerate(flags)}
    a, b = mk([1, 0, 0, 0, 1, 1, 0, 0]), mk([1, 1, 1, 1, 1, 1, 0, 0])
    d = delta(a, b, list(a))
    assert d[0] == 37.5 and d[3:5] == (0, 3) and abs(d[5] - .25) < 1e-12 and d[1] <= d[0] <= d[2]
    assert baselines(a, list(a)) == (25.0, 100.0)
    g = gated(b, a, .6, list(a))
    assert all(g[i] is a[i] for i in a) and gated(b, a, .5, list(a))["1"] is b["1"]
    print("analyze_context selfcheck ok")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--test", action="store_true", help="also the T6 test table")
    ap.add_argument("--selfcheck", action="store_true")
    args = ap.parse_args()
    if args.selfcheck:
        return selfcheck()
    out = []
    vruns = {c: r for c in VAL_CONDS if (r := load(c, "val-infect"))}
    if "zero" in vruns:
        ids = sorted(vruns["zero"])
        vruns = {c: r for c, r in vruns.items() if set(ids) <= set(r)}  # complete runs only
        chosen, h3 = val_tables(vruns, ids, out)
    else:
        chosen, h3, ids = {}, {}, []
        out.append("### val-infect: chưa có run `zero`\n")
    pruns = {c: r for c in PROBE_CONDS if (r := load(c, "pairs"))}
    probe = probe_tables(pruns, out) if "zero" in pruns else None
    if ids:
        verdicts(vruns, ids, h3, probe, out)
    if args.test:
        test_table(out)
    block = "\n".join([START, "", *out, END])
    text = open(REPORT, encoding="utf-8").read() if os.path.exists(REPORT) else f"# CONTEXT_SMALL 2026-11-09\n\n{START}\n{END}\n"
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    with open(REPORT, "w", encoding="utf-8") as fh:
        fh.write(head + block + tail)
    print("\n".join(out))


if __name__ == "__main__":
    main()
