#!/usr/bin/env python3
"""
analyze_finetune.py — what did LoRA fine-tuning on the train split change on test?

Reads the three logit-scored runs written by sft_mcq_lora.py (zero-shot, LoRA
with shuffled options, LoRA with the original option order) plus the seven
full zero-shot runs, and writes reports/eval/FINETUNE.md:

  1. accuracy, A-pick rate and calibration (ECE) per run;
  2. paired McNemar tests between runs, overall and per topic;
  3. near-duplicate check: gain on test items by their closest train item
     (TF-IDF cosine on question + options), so a gain carried only by
     near-copies of training items shows up;
  4. the contested items: 238 where DeepSeek-v4.1-flash and Gemma-4-31B agree
     on a non-key option, and 125 that all seven models miss. Does training on
     the train keys pull the model toward the key or toward the strong models?
  5. selective prediction and routing ("System One" style): answer with the
     small model when it is confident, send the rest to DeepSeek-v4.1-flash.

    python scripts/training/analyze_finetune.py
"""
import json
import os
import sys

from sklearn.feature_extraction.text import TfidfVectorizer

HERE = os.path.dirname(__file__)
sys.path.insert(0, os.path.join(HERE, "..", "eval"))
from compare_runs import mcnemar_exact  # noqa: E402
from run_eval import RUNS_DIR, load_rows  # noqa: E402
from summarize_eval import CANONICAL_34, load_run, wilson  # noqa: E402

OUT_MD = os.path.join(RUNS_DIR, "..", "FINETUNE.md")
BASE = "hf-logit__Qwen_Qwen3.5-2B"
FT_RUNS = {
    "zero-shot": f"{BASE}__paper__test",
    "LoRA, shuffled options": f"{BASE}+q35-2b-sft-shuf__paper__test",
    "LoRA, original order": f"{BASE}+q35-2b-sft-orig__paper__test",
}
SEVEN = {
    "DeepSeek-v4.1-flash": "nvidia__deepseek-ai_deepseek-v4.1-flash__paper__test",
    "Gemma-4-31B": "nvidia__google_gemma-4-31b-it__paper__test",
    "Gemma-4-12B": "gemma4_12b__paper__test",
    "Qwen3.5-9B": "qwen3.5_9b__paper__test",
    "Qwen3-8B": "qwen3_8b__paper__test",
    "Llama-3.1-8B": "llama3.1_8b__paper__test",
    "MedGemma-4B": "medgemma_4b__paper__test",
}


def load(name):
    return {r["id"]: r for r in load_run(os.path.join(RUNS_DIR, name + ".jsonl"))}


def pct(k, n):
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f} [{100 * lo:.0f}–{100 * hi:.0f}]" if n else "–"


def conf(r):
    return max(r["probs"])


def ece(recs, bins=10):
    total, err = len(recs), 0.0
    for b in range(bins):
        sel = [r for r in recs if b / bins < conf(r) <= (b + 1) / bins]
        if sel:
            err += len(sel) / total * abs(sum(map(conf, sel)) / len(sel) - sum(r["correct"] for r in sel) / len(sel))
    return err


def acc_at_coverage(recs, cov):
    top = sorted(recs, key=conf, reverse=True)[:max(1, round(cov * len(recs)))]
    return sum(r["correct"] for r in top) / len(top)


def paired_row(label, a, b, ids):
    ids = [i for i in ids if i in a and i in b]
    a_only = sum(a[i]["correct"] and not b[i]["correct"] for i in ids)
    b_only = sum(b[i]["correct"] and not a[i]["correct"] for i in ids)
    n = len(ids)
    if not n:
        return None
    acc_a, acc_b = sum(a[i]["correct"] for i in ids) / n, sum(b[i]["correct"] for i in ids) / n
    p = mcnemar_exact(a_only, b_only)
    return [label, n, f"{100 * acc_a:.1f}", f"{100 * acc_b:.1f}", f"{100 * (acc_b - acc_a):+.1f}",
            a_only, b_only, f"{p:.2g}" + (" *" if p < 0.05 else "")]


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    return out + ["| " + " | ".join(str(c) for c in row) + " |" for row in rows] + [""]


def item_text(r):
    return r["question"] + " " + " ".join(r["options"])


def main():
    # The original-order control may still be training; report what exists.
    ft = {label: load(name) for label, name in FT_RUNS.items()
          if os.path.exists(os.path.join(RUNS_DIR, name + ".jsonl"))}
    seven = {label: load(name) for label, name in SEVEN.items()}
    test = load_rows("test", None, 0)
    ids = [r["id"] for r in test]
    assert all(len(run) == len(ids) for run in ft.values()), {k: len(v) for k, v in ft.items()}
    zero, shuf, orig = ft["zero-shot"], ft["LoRA, shuffled options"], ft.get("LoRA, original order", {})
    lines = ["# VM14K: LoRA fine-tuning a 2B model on the train split", "",
             "Generated by `scripts/training/analyze_finetune.py` from runs written by "
             "`scripts/training/sft_mcq_lora.py`. Model: Qwen/Qwen3.5-2B, LoRA r=16 on every attention, "
             "Gated DeltaNet and MLP projection (15.6M trainable parameters, 0.82%), one epoch over the 7,313 "
             "usable train rows, batch 16, lr 2e-4, Intel Arc 140T iGPU. Scoring reads the next-token "
             "logits of the option letters after the paper's Fig. 6 prompt (thinking off), so no answer goes "
             "unparsed; compare these runs with each other, not with the generation-scored runs in "
             "`SUMMARY.md`. Test split: 1,658 questions, never used for training or tuning.", ""]

    # 1. Overall
    gold_a = sum(r["answer_index"] == 0 for r in test) / len(test)
    rand = sum(1 / len(r["options"]) for r in test) / len(test)
    rows = []
    for label, run in ft.items():
        recs = list(run.values())
        k = sum(r["correct"] for r in recs)
        rows.append([label, len(recs), pct(k, len(recs)), f"{100 * sum(r['pred'] == 'A' for r in recs) / len(recs):.1f}",
                     f"{100 * ece(recs):.1f}", f"{100 * acc_at_coverage(recs, 0.5):.1f}"])
    for label in ("Qwen3.5-9B", "DeepSeek-v4.1-flash"):
        recs = [seven[label][i] for i in ids if i in seven[label]]
        k = sum(r["correct"] for r in recs)
        rows.append([f"{label} (zero-shot, generation)", len(recs), pct(k, len(recs)),
                     f"{100 * sum(r['pred'] == 'A' for r in recs) / len(recs):.1f}", "–", "–"])
    lines += ["## 1. Overall", ""]
    lines += table(["run", "n", "accuracy [95% CI]", "picks A %", "ECE %", "acc. on 50% most confident"], rows)
    lines += [f"Floors on the same questions: always-A {100 * gold_a:.1f}, random {100 * rand:.1f}. "
              f"The key is A on {100 * gold_a:.1f}% of test items.", ""]

    # 1b. Letter-prior correction: how much of the gain needs no training at all?
    val_path = os.path.join(RUNS_DIR, f"{BASE}__paper__val.jsonl")
    if os.path.exists(val_path):
        prior = {}
        for r in load_run(val_path):
            prior.setdefault(r["n_options"], []).append(r["probs"])
        prior = {n: [sum(p[k] for p in ps) / len(ps) for k in range(n)] for n, ps in prior.items()}
        debiased = {}
        for i, r in zero.items():
            q = [p / m for p, m in zip(r["probs"], prior[r["n_options"]])]
            k = q.index(max(q))
            debiased[i] = dict(r, pred="ABCDEFG"[k], correct="ABCDEFG"[k] == r["gold"])
        lines += ["## 1b. Where the gain comes from", "",
                  "The zero-shot model prefers some letters regardless of content. Dividing each letter's "
                  "probability by its mean over the val split (no labels used, no training) removes that "
                  "preference. Mean zero-shot probability per letter on val: " +
                  "; ".join(f"{n} options " + " / ".join(f"{'ABCDEFG'[k]} {100 * m:.0f}%" for k, m in enumerate(ms))
                            for n, ms in sorted(prior.items()) if n in (2, 4)) + ".", ""]
        lines += table(["comparison (A → B)", "n", "A %", "B %", "B − A", "only A right", "only B right", "p"],
                       [paired_row("zero-shot → letter-prior corrected", zero, debiased, ids),
                        paired_row("letter-prior corrected → LoRA shuffled", debiased, shuf, ids)])
        lines += [f"Letter-prior corrected run picks A on "
                  f"{100 * sum(r['pred'] == 'A' for r in debiased.values()) / len(debiased):.1f}% of items.", ""]

    # 2. Paired tests
    lines += ["## 2. Paired comparison (McNemar exact)", ""]
    hdr = ["comparison (A → B)", "n", "A %", "B %", "B − A", "only A right", "only B right", "p"]
    rows = [paired_row("zero-shot → LoRA shuffled", zero, shuf, ids),
            paired_row("zero-shot → LoRA original order", zero, orig, ids),
            paired_row("LoRA shuffled → LoRA original order", shuf, orig, ids)]
    lines += table(hdr, [r for r in rows if r])
    rows = []
    for t in sorted(CANONICAL_34):
        tids = [r["id"] for r in test if t in r["medical_topic"]]
        if len(tids) >= 60:
            rows.append(paired_row(t, zero, shuf, tids))
    lines += ["Per topic, zero-shot → LoRA shuffled (topics with n ≥ 60; * p < 0.05, not corrected for "
              "multiple comparisons):", ""]
    lines += table(["topic"] + hdr[1:], sorted(rows, key=lambda r: -float(r[4])))

    # 3. Near-duplicates between train and test
    train = load_rows("train", None, 0)
    vec = TfidfVectorizer(ngram_range=(1, 2), min_df=1, sublinear_tf=True).fit([item_text(r) for r in train + test])
    sim = (vec.transform([item_text(r) for r in test]) @ vec.transform([item_text(r) for r in train]).T).tocsr()
    near = dict(zip(ids, sim.max(axis=1).toarray().ravel()))
    nearest = dict(zip(ids, (train[j] for j in sim.argmax(axis=1).A1)))
    lines += ["## 3. Is the gain carried by near-copies of training items?", "",
              "Each test item is binned by its highest TF-IDF cosine similarity (word 1–2-grams, question + "
              "options) to any train item. The split groups exact normalized stems only, so near-copies "
              "with small edits can sit on both sides.", ""]
    rows = []
    for lo, hi in ((0.0, 0.5), (0.5, 0.8), (0.8, 1.01)):
        bids = [i for i in ids if lo <= near[i] < hi]
        rows.append(paired_row(f"similarity {lo:.1f}–{min(hi, 1):.1f}", zero, shuf, bids))
    lines += table(["closest train item"] + hdr[1:], rows)
    key_text = lambda r: " ".join(r["options"][r["answer_index"]].lower().split())  # noqa: E731
    close = [r for r in test if near[r["id"]] >= 0.8]
    same = sum(key_text(r) == key_text(nearest[r["id"]]) for r in close)
    lines += [f"Of the {len(close)} test items with a train item at similarity ≥ 0.8, {same} "
              f"({100 * same / max(len(close), 1):.0f}%) have the same keyed answer text as that train item.", ""]

    # 4. Contested items
    ds, gm = seven["DeepSeek-v4.1-flash"], seven["Gemma-4-31B"]
    disagree = [i for i in ids if i in ds and i in gm and ds[i]["pred"] and ds[i]["pred"] == gm[i]["pred"]
                and not ds[i]["correct"]]
    allwrong = [i for i in ids if all(i in run and not run[i]["correct"] for run in seven.values())]
    assert (len(disagree), len(allwrong)) == (238, 125), (len(disagree), len(allwrong))
    rest = [i for i in ids if i not in set(disagree) | set(allwrong)]
    lines += ["## 4. Contested items: does training pull the model toward the key?", "",
              "`agree w/ strong` = picks the option that DeepSeek-v4.1-flash and Gemma-4-31B both chose. "
              "Letters are compared in the original option order (the logit runs present options unshuffled).", ""]
    rows = []
    for label, run in ft.items():
        rows.append([label,
                     pct(sum(run[i]["correct"] for i in disagree), len(disagree)),
                     pct(sum(run[i]["pred"] == ds[i]["pred"] for i in disagree), len(disagree)),
                     pct(sum(run[i]["correct"] for i in allwrong), len(allwrong)),
                     pct(sum(run[i]["correct"] for i in rest), len(rest))])
    lines += table(["run", f"238 disputed: = key", "238 disputed: agree w/ strong",
                    "125 all-wrong: = key", f"other {len(rest)}: = key"], rows)

    # 5. Selective prediction and routing
    lines += ["## 5. Answer when confident, otherwise ask the big model", "",
              "The small model answers the questions where its top-letter probability is highest; the least "
              "confident share goes to DeepSeek-v4.1-flash (its zero-shot answers on the same questions). "
              "`random routing` sends the same share at random (expected accuracy).", ""]
    for label in ("zero-shot", "LoRA, shuffled options"):
        run = ft[label]
        order = sorted(ids, key=lambda i: conf(run[i]))  # least confident first
        acc_small = sum(run[i]["correct"] for i in ids) / len(ids)
        acc_big = sum(ds[i]["correct"] for i in ids if i in ds) / len(ids)
        rows = []
        for share in (0.0, 0.25, 0.5, 0.75, 1.0):
            k = round(share * len(ids))
            routed = set(order[:k])
            acc = sum((ds[i]["correct"] if i in routed else run[i]["correct"]) for i in ids) / len(ids)
            kept = [run[i] for i in order[k:]]
            rows.append([f"{100 * share:.0f}%", f"{100 * acc:.1f}",
                         f"{100 * ((1 - share) * acc_small + share * acc_big):.1f}",
                         f"{100 * sum(r['correct'] for r in kept) / len(kept):.1f}" if kept else "–"])
        lines += [f"Small model: Qwen3.5-2B {label}", ""]
        lines += table(["sent to DeepSeek", "accuracy", "random routing", "small model on what it kept"], rows)

    # 6. Held-out topic (Kaggle runs from scripts/training/kaggle_heldout.py)
    kg_names = {"LoRA, all train (Kaggle)": f"{BASE}+kg-sft-shuf__paper__test",
                "LoRA, no OB/GYN in train (Kaggle)": f"{BASE}+kg-sft-shuf-noOBGYN__paper__test"}
    if all(os.path.exists(os.path.join(RUNS_DIR, n + ".jsonl")) for n in kg_names.values()):
        kg_all, kg_out = (load(n) for n in kg_names.values())
        topic = "Obstetrics and Gynecology"
        in_t = [r["id"] for r in test if topic in r["medical_topic"]]
        out_t = [r["id"] for r in test if topic not in r["medical_topic"]]
        lines += ["## 6. Held-out topic: does the gain on a topic need training items from it?", "",
                  f"Two LoRA runs on Kaggle T4 (fp16 autocast), same settings as above; the second drops every "
                  f"train row labelled {topic}. If the gain on the {len(in_t)} {topic} test items survives "
                  "without them, fine-tuning taught general habits rather than topic knowledge.", ""]
        rows = []
        for label, sub in ((f"{topic} ({len(in_t)})", in_t), (f"other topics ({len(out_t)})", out_t)):
            for a_name, a, b_name, b in (("zero-shot", zero, "all train", kg_all),
                                         ("zero-shot", zero, "no OB/GYN", kg_out),
                                         ("all train", kg_all, "no OB/GYN", kg_out)):
                rows.append(paired_row(f"{label}: {a_name} → {b_name}", a, b, sub))
        lines += table(["items: comparison"] + hdr[1:], rows)
        same = sum(kg_all[i]["pred"] == shuf[i]["pred"] for i in ids)
        lines += [f"Replication: the Kaggle all-train run scores "
                  f"{100 * sum(kg_all[i]['correct'] for i in ids) / len(ids):.1f} against "
                  f"{100 * sum(shuf[i]['correct'] for i in ids) / len(ids):.1f} on the laptop, and picks the same "
                  f"letter on {100 * same / len(ids):.1f}% of items.", ""]

    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
